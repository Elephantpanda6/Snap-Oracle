const std = @import("std");
const finding = @import("finding.zig");

pub const Lang = enum {
    c,
    zig,
    rust,
    py,

    pub fn fromString(s: []const u8) ?Lang {
        if (finding.eqlIgnoreCase(s, "c") or finding.eqlIgnoreCase(s, "cpp")) return .c;
        if (finding.eqlIgnoreCase(s, "zig")) return .zig;
        if (finding.eqlIgnoreCase(s, "rust") or finding.eqlIgnoreCase(s, "rs")) return .rust;
        if (finding.eqlIgnoreCase(s, "py") or finding.eqlIgnoreCase(s, "python")) return .py;
        return null;
    }
};

pub const GenKind = enum {
    harness,
    repro,
};

fn escapeStringLiteral(allocator: std.mem.Allocator, s: []const u8) ![]u8 {
    var out = std.ArrayList(u8).empty;
    errdefer out.deinit(allocator);
    for (s) |c| {
        switch (c) {
            '\\' => try out.appendSlice(allocator, "\\\\"),
            '"' => try out.appendSlice(allocator, "\\\""),
            '\n' => try out.appendSlice(allocator, "\\n"),
            '\r' => try out.appendSlice(allocator, "\\r"),
            '\t' => try out.appendSlice(allocator, "\\t"),
            else => try out.append(allocator, c),
        }
    }
    return out.toOwnedSlice(allocator);
}

pub fn generateHarness(
    allocator: std.mem.Allocator,
    lang: Lang,
    target_path: []const u8,
    entry_name: []const u8,
) ![]u8 {
    const base = finding.basename(target_path);
    const esc_base = try escapeStringLiteral(allocator, base);
    defer allocator.free(esc_base);
    const esc_entry = try escapeStringLiteral(allocator, entry_name);
    defer allocator.free(esc_entry);

    return switch (lang) {
        .c => std.fmt.allocPrint(allocator,
            \\/* Auto-generated by Snap-Oracle ARM64 */
            \\#include <stdint.h>
            \\#include <stddef.h>
            \\#include <stdio.h>
            \\#include <stdlib.h>
            \\
            \\#ifdef _WIN32
            \\#define WIN32_LEAN_AND_MEAN
            \\#include <windows.h>
            \\#else
            \\#include <dlfcn.h>
            \\#endif
            \\
            \\typedef uint64_t (*snap_entry_t)(const uint8_t *data, size_t len);
            \\static snap_entry_t g_entry = NULL;
            \\
            \\static snap_entry_t load_target_entry(const char *path) {{
            \\    if (g_entry) return g_entry;
            \\#ifdef _WIN32
            \\    HMODULE mod = LoadLibraryA(path);
            \\    if (!mod) return NULL;
            \\    g_entry = (snap_entry_t)(void *)GetProcAddress(mod, "{s}");
            \\#else
            \\    void *mod = dlopen(path, RTLD_NOW);
            \\    if (!mod) return NULL;
            \\    g_entry = (snap_entry_t)dlsym(mod, "{s}");
            \\#endif
            \\    return g_entry;
            \\}}
            \\
            \\int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {{
            \\    snap_entry_t fn = load_target_entry("{s}");
            \\    if (!fn) return 0;
            \\    (void)fn(data, size);
            \\    return 0;
            \\}}
            \\
            \\#ifdef SNAP_STANDALONE_MAIN
            \\int main(int argc, char **argv) {{
            \\    if (argc < 2) {{
            \\        fprintf(stderr, "Usage: %s <input_file>\\n", argv[0]);
            \\        return 1;
            \\    }}
            \\    FILE *f = fopen(argv[1], "rb");
            \\    if (!f) return 2;
            \\    if (fseek(f, 0, SEEK_END) != 0) {{ fclose(f); return 2; }}
            \\    long n = ftell(f);
            \\    if (n < 0 || fseek(f, 0, SEEK_SET) != 0) {{ fclose(f); return 2; }}
            \\    uint8_t *buf = (uint8_t *)malloc((size_t)(n > 0 ? n : 1));
            \\    if (!buf) {{ fclose(f); return 3; }}
            \\    size_t rd = (n > 0) ? fread(buf, 1, (size_t)n, f) : 0;
            \\    if (n > 0 && rd == 0 && ferror(f)) {{ free(buf); fclose(f); return 2; }}
            \\    fclose(f);
            \\    int rc = LLVMFuzzerTestOneInput(buf, rd);
            \\    free(buf);
            \\    return rc;
            \\}}
            \\#endif
            \\
        , .{ esc_entry, esc_entry, esc_base }),

        .zig => std.fmt.allocPrint(allocator,
            \\// Auto-generated Zig DynLib fuzz/replay harness by Snap-Oracle
            \\const std = @import("std");
            \\
            \\const TargetFn = *const fn ([*]const u8, usize) callconv(.c) u64;
            \\
            \\pub fn main(init: std.process.Init) !void {{
            \\    const allocator = std.heap.c_allocator;
            \\    var args = try init.minimal.args.iterateAllocator(allocator);
            \\    defer args.deinit();
            \\    _ = args.next();
            \\    const input_path = args.next() orelse return;
            \\    const data = try std.Io.Dir.cwd().readFileAlloc(init.io, input_path, allocator, .limited(1024 * 1024));
            \\    defer allocator.free(data);
            \\
            \\    var lib = try std.DynLib.open("{s}");
            \\    defer lib.close();
            \\    const entry = lib.lookup(TargetFn, "{s}") orelse return error.SymbolNotFound;
            \\    const rc = entry(data.ptr, data.len);
            \\    std.debug.print("target returned: {{d}}\\n", .{{rc}});
            \\}}
            \\
        , .{ esc_base, esc_entry }),

        .rust => std.fmt.allocPrint(allocator,
            \\// Auto-generated cargo-fuzz / Rust FFI harness by Snap-Oracle
            \\#![no_main]
            \\use libfuzzer_sys::fuzz_target;
            \\
            \\extern "C" {{
            \\    fn {s}(data: *const u8, len: usize) -> u64;
            \\}}
            \\
            \\// Link target: cargo rustc -- -l {s}
            \\fuzz_target!(|data: &[u8]| {{
            \\    unsafe {{
            \\        let _ = {s}(data.as_ptr(), data.len());
            \\    }}
            \\}});
            \\
        , .{ entry_name, base, entry_name }),

        .py => std.fmt.allocPrint(allocator,
            \\# Auto-generated ctypes ARM64/cross-OS runner by Snap-Oracle
            \\import ctypes
            \\import sys
            \\
            \\def main():
            \\    if len(sys.argv) < 2:
            \\        print("Usage: python repro_harness.py <input.bin>")
            \\        sys.exit(1)
            \\    with open(sys.argv[1], "rb") as f:
            \\        payload = f.read()
            \\    lib = ctypes.CDLL("./{s}")
            \\    fn = lib.{s}
            \\    fn.argtypes = [ctypes.c_char_p, ctypes.c_size_t]
            \\    fn.restype = ctypes.c_uint64
            \\    rc = fn(payload, len(payload))
            \\    print(f"Target returned: {{rc}}")
            \\
            \\if __name__ == "__main__":
            \\    main()
            \\
        , .{ esc_base, entry_name }),
    };
}

pub fn generateRepro(
    allocator: std.mem.Allocator,
    lang: Lang,
    target_path: []const u8,
    entry_name: []const u8,
    crash_bytes: []const u8,
) ![]u8 {
    const base = finding.basename(target_path);
    const esc_base = try escapeStringLiteral(allocator, base);
    defer allocator.free(esc_base);
    const esc_entry = try escapeStringLiteral(allocator, entry_name);
    defer allocator.free(esc_entry);

    const sha = finding.sha256Hex(crash_bytes);
    const max_embed: usize = 65536;
    const truncated = crash_bytes.len > max_embed;
    const capped = crash_bytes[0..@min(crash_bytes.len, max_embed)];
    const trunc_note = if (truncated)
        try std.fmt.allocPrint(allocator, "WARNING: input truncated from {d} to {d} bytes (64KB embed cap)", .{ crash_bytes.len, capped.len })
    else
        try allocator.dupe(u8, "full input embedded");
    defer allocator.free(trunc_note);

    var out = std.ArrayList(u8).empty;
    errdefer out.deinit(allocator);

    switch (lang) {
        .c => {
            const hdr = try std.fmt.allocPrint(allocator,
                \\/* Auto-generated standalone C crash reproducer by Snap-Oracle
                \\ * Target   : {s} ({s})
                \\ * Input SHA: {s} ({d} embedded / {d} total bytes; {s})
                \\ * Build    : zig cc -O2 repro.c -o repro
                \\ */
                \\#include <stdint.h>
                \\#include <stddef.h>
                \\#include <stdio.h>
                \\
                \\#ifdef _WIN32
                \\#define WIN32_LEAN_AND_MEAN
                \\#include <windows.h>
                \\#else
                \\#include <dlfcn.h>
                \\#endif
                \\
                \\typedef uint64_t (*snap_entry_t)(const uint8_t *, size_t);
                \\static const uint8_t CRASH_INPUT[] = {{
                \\
            , .{ esc_base, esc_entry, sha, capped.len, crash_bytes.len, trunc_note });
            defer allocator.free(hdr);
            try out.appendSlice(allocator, hdr);

            for (capped, 0..) |b, i| {
                const elem = try std.fmt.allocPrint(allocator, "{s}0x{x:0>2},", .{
                    if (i % 12 == 0) "\n    " else " ",
                    b,
                });
                defer allocator.free(elem);
                try out.appendSlice(allocator, elem);
            }
            if (capped.len == 0) try out.appendSlice(allocator, "\n    0x00");

            const tail = try std.fmt.allocPrint(allocator,
                \\
                \\}};
                \\
                \\int main(void) {{
                \\#ifdef _WIN32
                \\    HMODULE mod = LoadLibraryA("{s}");
                \\    if (!mod) {{ fprintf(stderr, "LoadLibraryA failed\\n"); return 2; }}
                \\    snap_entry_t fn = (snap_entry_t)(void *)GetProcAddress(mod, "{s}");
                \\#else
                \\    void *mod = dlopen("./{s}", RTLD_NOW);
                \\    if (!mod) {{ fprintf(stderr, "dlopen failed\\n"); return 2; }}
                \\    snap_entry_t fn = (snap_entry_t)dlsym(mod, "{s}");
                \\#endif
                \\    if (!fn) {{ fprintf(stderr, "Symbol {s} not found\\n"); return 3; }}
                \\    uint64_t rc = fn(CRASH_INPUT, {d});
                \\    printf("Returned cleanly: %llu\\n", (unsigned long long)rc);
                \\    return 0;
                \\}}
                \\
            , .{ esc_base, esc_entry, esc_base, esc_entry, esc_entry, capped.len });
            defer allocator.free(tail);
            try out.appendSlice(allocator, tail);
        },
        .zig => {
            const hdr = try std.fmt.allocPrint(allocator,
                \\// Standalone Zig reproducer by Snap-Oracle (SHA-256: {s}, {d}/{d} bytes; {s})
                \\const std = @import("std");
                \\const TargetFn = *const fn ([*]const u8, usize) callconv(.c) u64;
                \\const CRASH_INPUT = [_]u8{{
                \\
            , .{ sha, capped.len, crash_bytes.len, trunc_note });
            defer allocator.free(hdr);
            try out.appendSlice(allocator, hdr);
            for (capped, 0..) |b, i| {
                const elem = try std.fmt.allocPrint(allocator, "{s}0x{x:0>2},", .{
                    if (i % 12 == 0) "\n    " else " ",
                    b,
                });
                defer allocator.free(elem);
                try out.appendSlice(allocator, elem);
            }
            const tail = try std.fmt.allocPrint(allocator,
                \\
                \\}};
                \\
                \\pub fn main() !void {{
                \\    var lib = try std.DynLib.open("{s}");
                \\    defer lib.close();
                \\    const entry = lib.lookup(TargetFn, "{s}") orelse return error.SymbolNotFound;
                \\    _ = entry(&CRASH_INPUT, CRASH_INPUT.len);
                \\}}
                \\
            , .{ esc_base, esc_entry });
            defer allocator.free(tail);
            try out.appendSlice(allocator, tail);
        },
        .rust => {
            const hdr = try std.fmt.allocPrint(allocator,
                \\// Standalone Rust reproducer by Snap-Oracle (SHA-256: {s}, {d}/{d} bytes; {s})
                \\extern "C" {{ fn {s}(data: *const u8, len: usize) -> u64; }}
                \\static CRASH_INPUT: &[u8] = &[
                \\
            , .{ sha, capped.len, crash_bytes.len, trunc_note, entry_name });
            defer allocator.free(hdr);
            try out.appendSlice(allocator, hdr);
            for (capped, 0..) |b, i| {
                const elem = try std.fmt.allocPrint(allocator, "{s}0x{x:0>2},", .{
                    if (i % 12 == 0) "\n    " else " ",
                    b,
                });
                defer allocator.free(elem);
                try out.appendSlice(allocator, elem);
            }
            const tail = try std.fmt.allocPrint(allocator,
                \\
                \\];
                \\fn main() {{
                \\    unsafe {{ let _ = {s}(CRASH_INPUT.as_ptr(), CRASH_INPUT.len()); }}
                \\}}
                \\
            , .{entry_name});
            defer allocator.free(tail);
            try out.appendSlice(allocator, tail);
        },
        .py => {
            const hdr = try std.fmt.allocPrint(allocator,
                \\# Standalone Python ctypes reproducer by Snap-Oracle (SHA-256: {s}, {d}/{d} bytes; {s})
                \\import ctypes
                \\CRASH_INPUT = bytes([
                \\
            , .{ sha, capped.len, crash_bytes.len, trunc_note });
            defer allocator.free(hdr);
            try out.appendSlice(allocator, hdr);
            for (capped, 0..) |b, i| {
                const elem = try std.fmt.allocPrint(allocator, "{s}0x{x:0>2},", .{
                    if (i % 12 == 0) "\n    " else " ",
                    b,
                });
                defer allocator.free(elem);
                try out.appendSlice(allocator, elem);
            }
            const tail = try std.fmt.allocPrint(allocator,
                \\
                \\])
                \\lib = ctypes.CDLL("./{s}")
                \\fn = lib.{s}
                \\fn.argtypes = [ctypes.c_char_p, ctypes.c_size_t]
                \\fn.restype = ctypes.c_uint64
                \\print("rc =", fn(CRASH_INPUT, len(CRASH_INPUT)))
                \\
            , .{ esc_base, entry_name });
            defer allocator.free(tail);
            try out.appendSlice(allocator, tail);
        },
    }

    return out.toOwnedSlice(allocator);
}

pub fn runGenCommand(io: std.Io, allocator: std.mem.Allocator, args: []const []const u8) !void {
    if (args.len == 0) {
        std.debug.print("Usage: snap-oracle gen <harness|repro> --target <bin> [--entry fn] [--input <crash_file>] [--lang c|zig|rust|py] [--out <file>]\n", .{});
        return;
    }

    var kind: GenKind = .harness;
    var i: usize = 0;
    if (std.mem.eql(u8, args[0], "harness")) {
        kind = .harness;
        i = 1;
    } else if (std.mem.eql(u8, args[0], "repro")) {
        kind = .repro;
        i = 1;
    }

    var target_path: ?[]const u8 = null;
    var entry_name: []const u8 = "fuzz_entry";
    var input_path: ?[]const u8 = null;
    var lang: Lang = .c;
    var out_path: ?[]const u8 = null;

    while (i < args.len) : (i += 1) {
        const a = args[i];
        if (std.mem.eql(u8, a, "--target") and i + 1 < args.len) {
            i += 1;
            target_path = args[i];
        } else if (std.mem.eql(u8, a, "--entry") and i + 1 < args.len) {
            i += 1;
            entry_name = args[i];
        } else if (std.mem.eql(u8, a, "--input") and i + 1 < args.len) {
            i += 1;
            input_path = args[i];
        } else if (std.mem.eql(u8, a, "--lang") and i + 1 < args.len) {
            i += 1;
            lang = Lang.fromString(args[i]) orelse .c;
        } else if (std.mem.eql(u8, a, "--out") and i + 1 < args.len) {
            i += 1;
            out_path = args[i];
        }
    }

    const bin = target_path orelse {
        std.debug.print("Usage: snap-oracle gen <harness|repro> --target <bin> [--entry fn] [--input <file>] [--lang c|zig|rust|py]\n", .{});
        return;
    };

    const generated = switch (kind) {
        .harness => try generateHarness(allocator, lang, bin, entry_name),
        .repro => blk: {
            const ip = input_path orelse {
                std.debug.print("[gen repro] missing --input <crash_file>\n", .{});
                return;
            };
            const crash = try std.Io.Dir.cwd().readFileAlloc(io, ip, allocator, .limited(1024 * 1024));
            defer allocator.free(crash);
            if (crash.len > 65536) {
                std.debug.print("[gen repro] warning: input '{s}' ({d} bytes) exceeds 65536B embed limit and will be truncated\n", .{ ip, crash.len });
            }
            break :blk try generateRepro(allocator, lang, bin, entry_name, crash);
        },
    };
    defer allocator.free(generated);

    if (out_path) |p| {
        try finding.writeOutputFile(io, p, generated);
        std.debug.print("[gen] wrote {s} {s} ({d} bytes) -> {s}\n", .{ @tagName(lang), @tagName(kind), generated.len, p });
    } else {
        finding.writeStdout(io, generated);
    }
}
